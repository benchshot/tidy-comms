#!/usr/bin/env python3
"""Scan a project for comments and report line counts.

Prints a summary and writes every comment block, with hint tags, to a JSON file
for review. Read-only: never modifies the scanned files.
"""

import argparse
import fnmatch
import json
import os
import re
import subprocess
import sys
from collections import defaultdict

C_STYLE = {"line": ["//"], "block": ("/*", "*/"), "quotes": ['"', "'"], "multiline": []}
NESTING = dict(C_STYLE, nested=True)
HASH = {"line": ["#"], "block": None, "quotes": ['"', "'"], "multiline": []}
MARKUP = {"line": [], "block": ("<!--", "-->"), "quotes": ['"'], "multiline": []}

LANGUAGES = {
    "swift": dict(NESTING, quotes=['"'], multiline=['"""']),
    "kt": dict(NESTING, multiline=['"""']),
    "kts": dict(NESTING, multiline=['"""']),
    "scala": dict(NESTING, multiline=['"""']),
    "groovy": dict(C_STYLE, multiline=['"""', "'''"]),
    "gradle": dict(C_STYLE, multiline=['"""', "'''"]),
    "dart": dict(NESTING,multiline=['"""', "'''"]),
    "js": dict(C_STYLE, multiline=["`"]),
    "jsx": dict(C_STYLE, multiline=["`"]),
    "mjs": dict(C_STYLE, multiline=["`"]),
    "cjs": dict(C_STYLE, multiline=["`"]),
    "ts": dict(C_STYLE, multiline=["`"]),
    "tsx": dict(C_STYLE, multiline=["`"]),
    "go": dict(C_STYLE, multiline=["`"]),
    "rs": dict(NESTING, quotes=['"']),
    "php": dict(C_STYLE, line=["//", "#"]),
    "css": dict(C_STYLE, line=[]),
    "scss": C_STYLE,
    "less": C_STYLE,
    "py": dict(HASH, multiline=['"""', "'''"]),
    "rb": HASH,
    "sh": HASH,
    "bash": HASH,
    "zsh": HASH,
    "yml": HASH,
    "yaml": HASH,
    "toml": HASH,
    "r": HASH,
    "pl": HASH,
    "ex": dict(HASH, multiline=['"""']),
    "exs": dict(HASH, multiline=['"""']),
    "tf": dict(C_STYLE, line=["//", "#"]),
    "sql": {"line": ["--"], "block": ("/*", "*/"), "quotes": ["'"], "multiline": []},
    "lua": {"line": ["--"], "block": None, "quotes": ['"', "'"], "multiline": []},
    "xml": MARKUP,
    "html": MARKUP,
}
for ext in ("c", "h", "cc", "cpp", "cxx", "hpp", "m", "mm", "java", "cs"):
    LANGUAGES[ext] = C_STYLE

EXCLUDED_DIRS = {
    ".git", "node_modules", "Pods", "Carthage", ".build", "build", "DerivedData",
    "dist", "out", "vendor", ".venv", "venv", "__pycache__", "target", ".next",
    "coverage", ".gradle", ".idea", "SourcePackages", ".swiftpm",
}
MAX_FILE_BYTES = 1_000_000

DIRECTIVE = re.compile(
    r"swiftlint:|swift-format-ignore|periphery:|sourcery:|MARK:|eslint-|biome-ignore|"
    r"deno-lint-ignore|prettier-ignore|@ts-|@flow|istanbul ignore|c8 ignore|jshint|"
    r"noqa|type:\s*ignore|pylint:|pyright:|mypy:|rubocop:|frozen_string_literal|"
    r"coding[:=]|nolint|go:build|go:generate|\+build|#pragma|clang-format|NOSONAR|"
    r"noinspection|ktlint|@formatter:|detekt|\bignore(_for_file)?:\s*\w|"
    r"(//|#)\s*#?(end)?region\b|</?editor-fold"
)
LICENSE = re.compile(r"copyright|licen[cs]e|SPDX", re.IGNORECASE)
TODO = re.compile(r"\b(TODO|FIXME|HACK|XXX)\b")
GENERATED = re.compile(r"generated by|auto-?generated|do not edit", re.IGNORECASE)
CODE_LIKE = re.compile(
    r"[;{}]\s*$|^\s*(let|var|val|const|func|fun|def|fn|return|import|if|for|while|class|struct|"
    r"override|private|public|internal|protected|open|static|abstract|suspend|async|export|"
    r"interface|protocol|enum|extension|object|typealias|init|print|println|console\.|self\.|this\.|Log\.)\b|"
    r"^\s*@([A-Z]\w*|objc|available|discardableResult|escaping|inlinable)\b|"
    r"^\s*</?[A-Za-z][\w.:-]*(\s|/?>|$)"
)
TYPE_DECL = re.compile(r"\b(class|struct|enum|protocol|interface|extension|object|trait|mixin)\s+\w")
API_DECL = re.compile(
    r"\b(protocol|interface|trait)\s|\babstract\s+class\b|"
    r"\w*(Delegate|DataSource|Listener|Callbacks?|Observer)\b"
)
API_TEXT = re.compile(
    r"(^|\s)(public|open|@objc|protocol|interface|abstract)\b|"
    r"\w*(Delegate|DataSource|Listener|Callbacks?|Observer)\b"
)


def scan_line(line, spec, state):
    """Split one line into code and comment, carrying block/string state across lines."""
    has_code = False
    comment = None
    i = 0
    quote = None
    n = len(line)
    while i < n:
        if state["block"]:
            opener, closer = spec["block"]
            close = line.find(closer, i)
            nested = line.find(opener, i) if spec.get("nested") else -1
            if nested != -1 and (close == -1 or nested < close):
                comment = (comment or "") + line[i:nested + len(opener)]
                i = nested + len(opener)
                state["block"] += 1
                continue
            if close == -1:
                comment = (comment or "") + line[i:]
                return has_code, comment
            comment = (comment or "") + line[i:close + len(closer)]
            i = close + len(closer)
            state["block"] -= 1
            continue
        if state["multiline"]:
            delim = state["multiline"]
            close = line.find(delim, i)
            has_code = True
            if close == -1:
                return has_code, comment
            i = close + len(delim)
            state["multiline"] = None
            continue
        ch = line[i]
        if quote:
            if ch == "\\":
                i += 2
                continue
            if ch == quote:
                quote = None
            i += 1
            continue
        rest = line[i:]
        delim = next((d for d in spec["multiline"] if rest.startswith(d)), None)
        if delim:
            state["multiline"] = delim
            has_code = True
            i += len(delim)
            continue
        if any(rest.startswith(m) for m in spec["line"]):
            return has_code, (comment or "") + rest
        if spec["block"] and rest.startswith(spec["block"][0]):
            state["block"] = 1
            comment = (comment or "") + spec["block"][0]
            i += len(spec["block"][0])
            continue
        if ch in spec["quotes"]:
            quote = ch
            has_code = True
        elif not ch.isspace():
            has_code = True
        i += 1
    return has_code, comment


def tag_block(text, start, seen_code, is_first_line, enclosing=""):
    tags = []
    stripped = text.strip()
    if is_first_line and stripped.startswith("#!"):
        tags.append("shebang")
    if DIRECTIVE.search(text):
        tags.append("directive")
    if not seen_code and LICENSE.search(text):
        tags.append("license")
    if TODO.search(text):
        tags.append("todo")
    if re.match(r"(///|/\*\*|//!|#')", stripped):
        tags.append("doc")
    body = re.sub(r"^\s*(//+!?|/\*+|\*+/?|#+|--|<!--|-->)\s?", "", stripped, flags=re.MULTILINE)
    if any(CODE_LIKE.search(l) for l in body.splitlines() if l.strip()):
        tags.append("maybe-code")
        if API_TEXT.search(body) or API_DECL.search(enclosing):
            tags.append("api")
    return tags


def scan_file(path, spec):
    with open(path, encoding="utf-8", errors="replace") as f:
        lines = f.read().splitlines()
    if any(GENERATED.search(l) for l in lines[:5]):
        return None

    state = {"block": 0, "multiline": None}
    counts = {"lines": len(lines), "code": 0, "comment": 0, "blank": 0}
    blocks = []
    current = None
    seen_code = False
    enclosing = ""

    def flush():
        nonlocal current
        if current:
            text = "\n".join(current["text"])
            current["tags"] = tag_block(text, current["start"], current["seen_code"], current["start"] == 1, current["enclosing"])
            current["text"] = text
            if "api" in current["tags"] and current["enclosing"]:
                current["context"] = current["enclosing"].strip()
            del current["seen_code"]
            del current["enclosing"]
            current.pop("directive", None)
            blocks.append(current)
            current = None

    for number, line in enumerate(lines, 1):
        was_in_comment = state["block"]
        has_code, comment = scan_line(line, spec, state)
        if not has_code and comment is None and not was_in_comment:
            counts["blank"] += 1
            flush()
        elif not has_code:
            counts["comment"] += 1
            is_directive = not was_in_comment and DIRECTIVE.search(line)
            opens_block = not was_in_comment and spec["block"] and line.lstrip().startswith(spec["block"][0])
            if is_directive or opens_block or (current and current.get("directive")):
                flush()
            if current is None:
                current = {"start": number, "end": number, "kind": "full", "text": [], "seen_code": seen_code, "enclosing": enclosing}
            current["end"] = number
            current["text"].append(line.rstrip())
            if is_directive:
                current["directive"] = True
            if number == 1 and line.startswith("#!"):
                flush()
        else:
            counts["code"] += 1
            flush()
            seen_code = True
            if TYPE_DECL.search(line):
                enclosing = line
            elif line.startswith("}"):
                enclosing = ""
            if comment and comment.strip() not in ("", "*/"):
                blocks.append({
                    "start": number, "end": number, "kind": "trailing", "text": comment.strip(),
                    "tags": tag_block(comment, number, True, False, enclosing),
                })
    flush()
    return counts, blocks


def all_paths(root):
    try:
        out = subprocess.run(
            ["git", "-C", root, "ls-files", "-co", "--exclude-standard"],
            capture_output=True, text=True, check=True,
        ).stdout
        candidates = out.splitlines()
    except (subprocess.CalledProcessError, FileNotFoundError):
        candidates = []
        for dirpath, dirnames, filenames in os.walk(root):
            dirnames[:] = [d for d in dirnames if d not in EXCLUDED_DIRS]
            candidates.extend(os.path.relpath(os.path.join(dirpath, f), root) for f in filenames)
    return [p for p in sorted(candidates) if not set(p.split(os.sep)[:-1]) & EXCLUDED_DIRS]


def list_files(paths, root):
    for rel in paths:
        if ".min." in rel:
            continue
        path = os.path.join(root, rel)
        ext = rel.rsplit(".", 1)[-1].lower() if "." in os.path.basename(rel) else ""
        if ext in LANGUAGES and os.path.isfile(path) and os.path.getsize(path) <= MAX_FILE_BYTES:
            yield rel, ext


DOCS_BUILD = re.compile(r"swift-docc-plugin|docbuild|generate-documentation|dokka|\bjazzy\b|dartdoc|typedoc|\bjsdoc\b")
BUILD_FILES = re.compile(
    r"(^|/)(Package\.swift|[^/]+\.gradle(\.kts)?|Makefile|Fastfile|pubspec\.yaml|package\.json|"
    r"\.github/workflows/[^/]+\.ya?ml|\.gitlab-ci\.yml|bitrise\.yml|[^/]+\.sh)$"
)


def docs_evidence(paths, root):
    """Signs that generated API docs are actually built, not just written in doc-comment style."""
    found = sorted({p.split(".docc/")[0] + ".docc" for p in paths if ".docc/" in p})
    found = [f"{d}: DocC catalog" for d in found]
    for rel in paths:
        if not BUILD_FILES.search(rel):
            continue
        try:
            with open(os.path.join(root, rel), encoding="utf-8", errors="replace") as f:
                match = DOCS_BUILD.search(f.read(MAX_FILE_BYTES))
        except OSError:
            continue
        if match:
            found.append(f"{rel}: {match.group(0)}")
    return found


CONFIG_NAME = ".tidycomms.json"
PROTECTED_TAGS = {"shebang", "directive", "license", "kept"}


def git(root, *args):
    return subprocess.run(["git", "-C", root, *args], capture_output=True, text=True, check=True).stdout


def load_config(path):
    if not os.path.isfile(path):
        return {}
    with open(path) as f:
        return json.load(f)


def normalize(text):
    return "\n".join(line.strip() for line in text.strip().splitlines())


def changed_scope(root, since):
    """Files and line numbers changed since `since` (a git ref), or since HEAD for uncommitted work."""
    base = git(root, "merge-base", since, "HEAD").strip() if since else "HEAD"
    files = set(git(root, "diff", "--name-only", "--relative", base).splitlines())
    untracked = set(git(root, "ls-files", "-o", "--exclude-standard").splitlines())
    lines = defaultdict(set)
    current = None
    for row in git(root, "diff", "-U0", "--relative", base).splitlines():
        if row.startswith("+++ "):
            current = row[6:] if row.startswith("+++ b/") else None
        elif row.startswith("@@") and current:
            added = row.split("+", 1)[1].split(" ", 1)[0]
            start, _, count = added.partition(",")
            count = int(count) if count else 1
            lines[current].update(range(int(start), int(start) + count))
    return files | untracked, untracked, lines


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("root", nargs="?", default=".")
    parser.add_argument("--out", required=True, help="where to write the JSON report")
    scope = parser.add_mutually_exclusive_group()
    scope.add_argument("--changed", action="store_true", help="only files with uncommitted changes")
    scope.add_argument("--since", metavar="REF", help="only files changed since REF (e.g. main), plus uncommitted work")
    parser.add_argument("--changed-lines", action="store_true",
                        help="with --changed/--since, only report comments on changed lines")
    parser.add_argument("--config", help=f"config file (default: <root>/{CONFIG_NAME})")
    args = parser.parse_args()
    root = os.path.abspath(args.root)
    if args.changed_lines and not (args.changed or args.since):
        parser.error("--changed-lines needs --changed or --since")

    config = load_config(args.config or os.path.join(root, CONFIG_NAME))
    skip = config.get("skip", [])
    keep = [(k.get("file"), normalize(k["text"])) for k in config.get("keep", [])]

    paths = all_paths(root)
    scoped = untracked = changed_lines = None
    if args.changed or args.since:
        scoped, untracked, changed_lines = changed_scope(root, args.since)

    totals = defaultdict(int)
    by_language = defaultdict(lambda: defaultdict(int))
    files, skipped_generated, skipped_config = [], 0, 0
    for rel, ext in list_files(paths, root):
        if scoped is not None and rel not in scoped:
            continue
        if any(fnmatch.fnmatch(rel, pattern) for pattern in skip):
            skipped_config += 1
            continue
        result = scan_file(os.path.join(root, rel), LANGUAGES[ext])
        if result is None:
            skipped_generated += 1
            continue
        counts, blocks = result
        for block in blocks:
            text = normalize(block["text"])
            if any(text == k_text and file in (None, rel) for file, k_text in keep):
                block["tags"].append("kept")
        if args.changed_lines and rel not in untracked:
            in_scope = changed_lines.get(rel, set())
            blocks = [b for b in blocks if any(n in in_scope for n in range(b["start"], b["end"] + 1))]
        for key, value in counts.items():
            totals[key] += value
            by_language[ext][key] += value
        by_language[ext]["files"] += 1
        files.append({"path": rel, "language": ext, **counts, "blocks": blocks})

    evidence = docs_evidence(paths, root)
    evidence += [f"{m}: listed in {CONFIG_NAME}" for m in config.get("docs_modules", [])]
    all_blocks = [b for f in files for b in f["blocks"]]
    summary = {
        "root": root,
        "scope": f"since {args.since}" if args.since else "uncommitted changes" if args.changed else "all files",
        "changed_lines_only": args.changed_lines,
        "files": len(files),
        "skipped_generated": skipped_generated,
        "skipped_by_config": skipped_config,
        **totals,
        "comment_blocks": sum(b["kind"] == "full" for b in all_blocks),
        "trailing_comments": sum(b["kind"] == "trailing" for b in all_blocks),
        "protected_blocks": sum(bool(PROTECTED_TAGS & set(b["tags"])) for b in all_blocks),
        "kept_by_config": sum("kept" in b["tags"] for b in all_blocks),
        "by_language": by_language,
        "docs_evidence": evidence,
    }
    with open(args.out, "w") as f:
        json.dump({"summary": summary, "files": files}, f, indent=1)

    skipped = [f"{n} {why}" for n, why in ((skipped_generated, "generated"), (skipped_config, "by config")) if n]
    print(f"Scanned {len(files)} files in {root} ({summary['scope']}"
          + (", changed lines only" if args.changed_lines else "") + ")"
          + (f", skipped {', '.join(skipped)}" if skipped else ""))
    print(f"Lines: {totals['lines']:,}  code: {totals['code']:,}  "
          f"comment: {totals['comment']:,}  blank: {totals['blank']:,}")
    print(f"Comment blocks: {summary['comment_blocks']:,}  trailing comments: "
          f"{summary['trailing_comments']:,}  protected: {summary['protected_blocks']:,}"
          + (f"  kept by config: {summary['kept_by_config']:,}" if summary["kept_by_config"] else ""))
    if evidence:
        print("Generated docs are built here:")
        for item in evidence:
            print(f"  {item}")
    else:
        print("No sign that generated API docs are built.")
    print("\nMost commented files:")
    for f in sorted(files, key=lambda f: f["comment"], reverse=True)[:10]:
        if f["comment"]:
            print(f"  {f['comment']:>6,}  {f['path']}")
    print(f"\nFull report: {args.out}")


if __name__ == "__main__":
    sys.exit(main())
